"""Build results/RESULTS.md from one or more benchmark result directories.

Every number in the report is read from ``metrics.json`` / ``meta.json`` of the
given directories (``rescore`` is run first so the current matcher is used).
Test-split numbers are reported separately from dev/smoke splits, which are
never presented as test metrics.
"""

from __future__ import annotations

import json
from collections import Counter
from collections.abc import Sequence
from datetime import UTC, datetime
from pathlib import Path
from typing import Any, Optional

from benchmarks.runner import METRICS_FILE, load_meta, rescore

_SPLIT_TITLES = {
    "test": "Test split",
    "dev": "Dev split (pipeline was tuned on these — not test metrics)",
    "smoke": "Smoke split (plumbing checks, often contaminated — not test metrics)",
}


def _pct(v: Optional[float]) -> str:
    return "–" if v is None else f"{100 * v:.1f}%"


def _num(v: Optional[float], digits: int = 2) -> str:
    return "–" if v is None else f"{v:.{digits}f}"


def _stat(s: Optional[dict[str, Any]], fmt=_pct) -> str:
    if not s or s.get("mean") is None:
        return "–"
    if s.get("n", 0) > 1 and s["min"] != s["max"]:
        return f"{fmt(s['mean'])} ({fmt(s['min'])}–{fmt(s['max'])})"
    return fmt(s["mean"])


def _usd(v: Optional[float]) -> str:
    return "–" if v is None else f"${v:.2f}"


def _secs(v: Optional[float]) -> str:
    if v is None:
        return "–"
    return f"{v / 60:.1f} min" if v >= 60 else f"{v:.0f} s"


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out


class _Run:
    def __init__(self, path: Path, meta: dict[str, Any], metrics: dict[str, Any]) -> None:
        self.path, self.meta, self.metrics = path, meta, metrics
        self.preset = meta.get("preset", {}).get("name", "?")
        self.model = meta.get("models", {}).get("hunter", "?")
        git = meta.get("git") or {}
        commit = (git.get("commit") or "unknown")[:10]
        self.commit = commit + (" (dirty)" if git.get("dirty") else "")
        self.date = (meta.get("created_at") or "")[:10]
        self.label = f"{self.preset} · {self.model} · {path.name}"


def _severity_recall(runs: list[dict[str, Any]], sev: str, key: str) -> Optional[dict[str, Any]]:
    """Pooled recall for one severity per run index, then mean/min/max over run indices."""
    by_k: dict[int, list[tuple[float, int]]] = {}
    for r in runs:
        if r["status"] != "ok":
            continue
        rs = (r.get("recall_by_severity") or {}).get(sev)
        if not rs or not rs["num_gt"] or rs.get(key) is None:
            continue
        by_k.setdefault(r["run_index"], []).append((rs[key] * rs["num_gt"], rs["num_gt"]))
    vals = [sum(h for h, _ in v) / sum(n for _, n in v) for v in by_k.values() if sum(n for _, n in v)]
    if not vals:
        return None
    return {"mean": sum(vals) / len(vals), "min": min(vals), "max": max(vals), "n": len(vals)}


def build_report(results_dirs: Sequence[Path], *, do_rescore: bool = True) -> str:
    runs_info: list[_Run] = []
    for d in results_dirs:
        d = Path(d)
        meta = load_meta(d)
        metrics = rescore(d) if do_rescore or not (d / METRICS_FILE).exists() \
            else json.loads((d / METRICS_FILE).read_text(encoding="utf-8"))
        runs_info.append(_Run(d, meta, metrics))

    now = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    lines: list[str] = [
        "# Benchmark results",
        "",
        f"Generated by `audit-agent benchmark report` on {now}. Every number below is "
        "computed from the raw run files in the listed directories; see the README "
        "(*Evaluation*) for the matching rule and metric definitions.",
        "",
        "## Runs",
        "",
    ]
    lines += _table(
        ["Results dir", "Preset", "Hunter model", "Commit", "Date", "Runs/contest", "Contests"],
        [[f"`{r.path.name}`", r.preset, r.model, f"`{r.commit}`", r.date,
          str(r.meta.get("runs", "?")), str(len(r.meta.get("contests", [])))] for r in runs_info],
    )

    splits = sorted({s for r in runs_info for s in r.metrics.get("splits", {})},
                    key=lambda s: ["test", "dev", "smoke"].index(s) if s in _SPLIT_TITLES else 9)
    for split in splits:
        lines += ["", f"## {_SPLIT_TITLES.get(split, split)}", ""]
        with_split = [r for r in runs_info if split in r.metrics.get("splits", {})]

        lines += ["### Summary by preset", "",
                  "Mean over runs, (min–max) when runs differ. Recall/precision are macro "
                  "averages over contests; cost and time are per contest.", ""]
        rows = []
        for r in with_split:
            sp = r.metrics["splits"][split]
            s = sp["summary"]
            rows.append([
                r.label, str(sp["num_contests"]), f"{sp['num_runs_ok']}/{sp['num_runs_error']}",
                _stat(s.get("human_recall_hypotheses")), _stat(s.get("human_recall_final")),
                _stat(s["recall_hypotheses_at_30"]), _stat(s["recall_final"]),
                _stat(s["recall_validated"]), _stat(s["precision_gt"]),
                _stat(s["precision_adjusted"]),
                _stat(s["validator_loss_count"], lambda v: _num(v, 1)),
                _stat(s["cost_usd"], _usd), _stat(s["time_s"], _secs),
            ])
        lines += _table(["Preset · model · dir", "Contests", "Runs ok/failed",
                         "Recall hyp@30 (human)", "Recall final (human)",
                         "Recall hyp@30 (matcher)", "Recall final (matcher)",
                         "Recall validated", "Precision (GT)",
                         "Precision (adjusted)", "Validator loss (GT)", "Cost", "Time"], rows)

        lines += ["", "### Pooled recall", "",
                  "Total GT matched / total GT over all contests of the split, per run.", ""]
        rows = []
        for r in with_split:
            ps = r.metrics["splits"][split]["pooled_summary"]
            rows.append([r.label, _stat(ps["recall_hypotheses_at_30"]), _stat(ps["recall_final"]),
                         _stat(ps["recall_validated"])])
        lines += _table(["Preset · model · dir", "Recall hyp@30", "Recall final", "Recall validated"], rows)

        lines += ["", "### Recall by severity", ""]
        rows = []
        for r in with_split:
            split_runs = [x for x in r.metrics["runs"]
                          if r.metrics["contests"].get(x["contest_id"], {}).get("split") == split]
            rows.append([r.label] + [
                _stat(_severity_recall(split_runs, sev, key))
                for sev in ("high", "medium")
                for key in ("recall_hypotheses_at_30", "recall_final")
            ])
        lines += _table(["Preset · model · dir", "High hyp@30", "High final",
                         "Medium hyp@30", "Medium final"], rows)

        for r in with_split:
            lines += ["", f"### Per contest — {r.label}", ""]
            rows = []
            for cid, c in sorted(r.metrics["contests"].items()):
                if c["split"] != split:
                    continue
                a = c["aggregate"]
                runs = [x for x in r.metrics["runs"] if x["contest_id"] == cid]
                ok = [x for x in runs if x["status"] == "ok"]
                exp = Counter()
                for x in ok:
                    exp.update((x.get("exploit_stats") or {}).get("counts") or {})
                flags = "".join(["†" if c.get("needs_review") else "",
                                 "‡" if c.get("contaminated") else ""])
                rows.append([
                    f"{cid}{flags}", str(c["num_ground_truth"]), f"{len(ok)}/{len(runs)}",
                    _stat(a["recall_hypotheses_at_30"]), _stat(a["recall_final"]),
                    _stat(a["recall_validated"]), _stat(a["precision_gt"]),
                    _stat(a["validator_loss_count"], lambda v: _num(v, 1)),
                    f"{exp.get('exploited', 0)}/{sum(exp.values())}",
                    _stat(a["cost_usd"], _usd), _stat(a["time_s"], _secs),
                ])
            lines += _table(["Contest", "GT", "Runs ok", "Recall hyp@30", "Recall final",
                             "Recall validated", "Precision (GT)", "Validator loss",
                             "PoCs exploited/total", "Cost", "Time"], rows)
            if any(c.get("needs_review") or c.get("contaminated")
                   for c in r.metrics["contests"].values() if c["split"] == split):
                lines += ["", "† ground truth not yet reviewed (`needs_review`); "
                          "‡ contaminated (public solutions)."]

            conf = {"skeptic": Counter(), "final": Counter()}
            for x in r.metrics["runs"]:
                if r.metrics["contests"].get(x["contest_id"], {}).get("split") != split:
                    continue
                for stage, m in (x.get("validator_confusion") or {}).items():
                    for status, cols in m.items():
                        for col, n in cols.items():
                            conf[stage][(status, col)] += n
            if any(conf[s] for s in conf):
                lines += ["", "Validator confusion (summed over runs; columns: matches some GT / "
                          "matches none):", ""]
                rows = []
                for stage in ("skeptic", "final"):
                    for status in ("validated", "unverified", "false_positive"):
                        rows.append([stage, status, str(conf[stage][(status, "gt_match")]),
                                     str(conf[stage][(status, "no_gt_match")])])
                lines += _table(["Stage", "Verdict", "GT match", "No GT match"], rows)

    lines += ["", "## Configuration", ""]
    for r in runs_info:
        m = r.meta
        lines += [f"**`{r.path.name}`** — preset `{r.preset}`, created {m.get('created_at', '?')}, "
                  f"commit `{r.commit}`, Python {m.get('python', '?')}, "
                  f"dataset `{(m.get('dataset') or {}).get('ref', '?')}` "
                  f"(sha256 `{((m.get('dataset') or {}).get('sha256') or '?')[:12]}`).", ""]
        models = m.get("models") or {}
        lines.append("Models: " + ", ".join(f"{k}=`{v or '(default)'}`" for k, v in sorted(models.items())))
        flags = m.get("flags") or {}
        lines.append("")
        lines.append("Flags: " + ", ".join(f"`{k}={str(v).lower()}`" for k, v in sorted(flags.items())))
        lines.append("")
        knobs = m.get("settings") or {}
        if knobs:
            lines.append("Settings: " + ", ".join(f"`{k}={v}`" for k, v in sorted(knobs.items())))
            lines.append("")

    lines += ["## Limitations of these numbers", ""]
    lines += _limitations(runs_info)
    lines.append("")
    return "\n".join(lines)


def _limitations(runs_info: list[_Run]) -> list[str]:
    out: list[str] = []
    for r in runs_info:
        m, mx = r.meta, r.metrics
        n_runs = m.get("runs", 1)
        # GT flags as of the last rescore (may use --dataset), not the snapshot taken at run time
        contests = list((mx.get("contests") or {}).values()) or m.get("contests", [])
        notes = []
        if n_runs == 1:
            notes.append("1 run per contest — LLM output is non-deterministic, no spread is shown")
        else:
            notes.append(f"{n_runs} runs per contest")
        nr = sum(1 for c in contests if c.get("needs_review"))
        if nr:
            notes.append(f"{nr} contest(s) with unreviewed ground truth (`needs_review`)")
        cont = sum(1 for c in contests if c.get("contaminated"))
        if cont:
            notes.append(f"{cont} contaminated contest(s)")
        failed = sum(1 for x in mx.get("runs", []) if x["status"] != "ok")
        if failed:
            notes.append(f"{failed} failed run(s), excluded from averages")
        unrev = mx.get("unreviewed_label_rows", 0)
        if unrev:
            notes.append(f"{unrev} hypothesis row(s) not yet reviewed in labels_*.csv — "
                         "human recall is not computed for those runs")
        unl = mx.get("unlabelled_unmatched_findings", 0)
        if unl:
            notes.append(f"{unl} unmatched validated finding(s) not labelled in "
                         "`unmatched_findings.csv` — precision_adjusted is missing for those runs "
                         "and precision_gt is only a lower bound")
        if (m.get("git") or {}).get("dirty"):
            notes.append("uncommitted changes in the working tree at run time")
        if not (m.get("git") or {}).get("commit"):
            notes.append("git commit unknown")
        unpriced = set()
        for p in sorted(r.path.glob("*/run_*.json")):
            try:
                usage = json.loads(p.read_text(encoding="utf-8")).get("usage") or {}
            except (OSError, ValueError):
                continue
            unpriced.update(usage.get("unpriced_models") or [])
        if unpriced:
            notes.append("cost unknown for models without a price: " + ", ".join(f"`{u}`" for u in sorted(unpriced)))
        out.append(f"- `{r.path.name}`: " + "; ".join(notes) + ".")
    commits = {r.commit for r in runs_info}
    models = {r.model for r in runs_info}
    if len(runs_info) > 1 and (len(commits) > 1 or len(models) > 1):
        out.append("- Compared directories differ in commit and/or Hunter model; preset "
                   "differences are confounded with those.")
    out.append("- Ground truth comes from official contest reports, which miss valid issues; "
               "unmatched findings are not necessarily false positives.")
    return out


def write_report(results_dirs: Sequence[Path], out: Path, *, do_rescore: bool = True) -> Path:
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(build_report(results_dirs, do_rescore=do_rescore), encoding="utf-8")
    return out
