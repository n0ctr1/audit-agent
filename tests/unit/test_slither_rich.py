"""Offline tests for the rich Slither-API model parsing (no Docker required).

Uses tests/fixtures/slither_rich.json, generated by docker/slither/rich_analysis.py
against test-contracts/test-lending (a Foundry lending pool). Verifies that the
normalized parser ingests the rich format and that the new fields (taint,
external_targets, full call graph) survive into SlitherAnalysis / InMemoryGraph.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from audit_agent.knowledge.graph.builders import parse_slither_json
from audit_agent.knowledge.graph.context import InMemoryGraph

FIXTURE = Path(__file__).resolve().parents[1] / "fixtures" / "slither_rich.json"


@pytest.fixture
def rich_model() -> dict:
    return json.loads(FIXTURE.read_text())


def _fn(analysis, name):
    return next(f for c in analysis.contracts for f in c.functions if f.name == name)


def test_rich_parses_full_function_set(rich_model):
    """Rich model exposes EVERY declared function, not just detector hits."""
    analysis = parse_slither_json(rich_model)
    fn_names = {f.name for c in analysis.contracts for f in c.functions}
    # Public entrypoints AND internal helpers must be present.
    assert {"borrow", "liquidate", "depositCollateral", "_getCollateralValue"} <= fn_names
    assert len(analysis.all_functions()) >= 15


def test_rich_reads_writes_are_accurate(rich_model):
    analysis = parse_slither_json(rich_model)
    borrow = _fn(analysis, "borrow")
    # borrow writes borrowedAmount and reads the collateral ratio / oracle var.
    assert any("borrowedAmount" in w for w in borrow.writes)
    assert borrow.reads, "rich model must capture state reads"


def test_rich_taint_and_oracle_flags(rich_model):
    analysis = parse_slither_json(rich_model)
    borrow = _fn(analysis, "borrow")
    # borrowedAmount is reachable from the user-supplied amount → tainted.
    assert "borrowedAmount" in borrow.tainted_state_writes
    # borrow/liquidate call priceOracle.getPrice → oracle flag set.
    assert borrow.reads_oracle is True


def test_rich_external_targets_name_the_dependency(rich_model):
    analysis = parse_slither_json(rich_model)
    liq = _fn(analysis, "liquidate")
    dests = {t["dest"] for t in liq.external_targets}
    fns = {t["fn"] for t in liq.external_targets}
    # The state variable holding the external contract is captured by name.
    assert "priceOracle" in dests
    assert "getPrice" in fns


def test_rich_internal_call_graph_resolves(rich_model):
    analysis = parse_slither_json(rich_model)
    borrow = _fn(analysis, "borrow")
    # borrow → _getCollateralValue is a resolved internal edge (function ID).
    assert any("_getCollateralValue" in c for c in borrow.calls)


def test_inmemory_graph_reverse_edges(rich_model):
    """The graph must build caller/writer reverse indices from rich edges."""
    analysis = parse_slither_json(rich_model)
    graph = InMemoryGraph(analysis)
    helper = _fn(analysis, "_getCollateralValue")
    callers = graph._callers_of.get(helper.id, set())
    # borrow and liquidate both call the collateral-value helper.
    caller_names = {graph._fns[c].name for c in callers}
    assert {"borrow", "liquidate"} <= caller_names


def test_rich_scoring_prioritizes_value_functions(rich_model):
    """Accurate flags should give money-moving functions real attack surface."""
    analysis = parse_slither_json(rich_model)
    borrow = _fn(analysis, "borrow")
    liq = _fn(analysis, "liquidate")
    # With real reads/writes/external-calls/oracle, these score well above zero.
    assert borrow.attack_surface_score > 0
    assert liq.attack_surface_score > 0
